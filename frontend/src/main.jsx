/**
 * =============================================================================
 * @file main.jsx
 * =============================================================================
 *
 * Точка входа (Entry Point) frontend-приложения
 * Kafka System Control.
 *
 * =============================================================================
 * Назначение
 * =============================================================================
 *
 * Этот файл отвечает только за первоначальный запуск React-приложения.
 *
 * Основные задачи:
 *
 * • подключение глобальных CSS;
 * • инициализация i18n;
 * • подключение глобальных Context Provider'ов;
 * • удаление статического Splash Screen из index.html;
 * • монтирование корневого React-компонента.
 *
 * =============================================================================
 * Важный принцип загрузки
 * =============================================================================
 *
 * До запуска React браузер отображает статический элемент:
 *
 *     #initial-splash
 *
 * Он находится непосредственно в index.html и нужен для того,
 * чтобы пользователь не видел пустой белый экран в момент,
 * когда JavaScript ещё загружается.
 *
 * После успешного монтирования React статический Splash удаляется.
 *
 * После этого управление загрузочным экраном полностью переходит
 * компоненту LoadingDemo.
 *
 * Схема запуска:
 *
 *     index.html
 *          │
 *          ▼
 *     #initial-splash
 *          │
 *          │ загружается React
 *          ▼
 *     main.jsx
 *          │
 *          ├── удаляет #initial-splash
 *          │
 *          ▼
 *     LoadingDemo
 *          │
 *          ▼
 *     LoadingScreen
 *
 * =============================================================================
 * Что НЕ должно находиться в этом файле
 * =============================================================================
 *
 * Здесь не должна размещаться:
 *
 * • бизнес-логика;
 * • маршрутизация;
 * • работа с Kafka;
 * • API-запросы;
 * • логика отдельных страниц;
 * • состояние компонентов приложения.
 *
 * =============================================================================
 */

/* =============================================================================
   Библиотеки React
============================================================================= */

import React from 'react';
import ReactDOM from 'react-dom/client';

/* =============================================================================
   Глобальные стили
============================================================================= */

import './styles/global.css';
import './styles/themes.css';
import './styles/layout.css';
import './styles/sidebar.css';

/* =============================================================================
   Инициализация локализации
============================================================================= */

import './i18n/index.js';

/* =============================================================================
   Глобальные Context Provider'ы
============================================================================= */

import { ThemeProvider } from './contexts/ThemeContext';
import { LanguageProvider } from './contexts/LanguageContext';

/* =============================================================================
   Загрузочный экран
============================================================================= */

/*
 * На текущем этапе разработки используется LoadingDemo.
 *
 * Это временная точка входа для проверки UI Splash Screen.
 *
 * После завершения разработки LoadingDemo будет заменён
 * на основной App.
 */
import LoadingDemo from './components/loading/LoadingDemo';

/*
 * Основной App пока намеренно НЕ подключаем.
 *
 * Когда загрузочный экран будет полностью готов,
 * здесь снова будет:
 *
 * import App from './App';
 *
 * и LoadingDemo будет заменён на <App />.
 */
// import App from './App';


/* =============================================================================
   Удаление статического Splash Screen
============================================================================= */

/**
 * Удаляет статический Splash Screen, который находится
 * непосредственно в index.html.
 *
 * Почему это выполняется здесь:
 *
 * index.html загружается раньше React.
 *
 * Поэтому статический #initial-splash необходим для того,
 * чтобы пользователь сразу видел экран загрузки,
 * а не пустую страницу.
 *
 * После запуска React статический элемент больше не нужен,
 * поскольку его заменяет React-компонент LoadingDemo.
 *



/* =============================================================================
   Поиск корневого DOM-элемента React
============================================================================= */

const rootElement = document.getElementById('root');

/*
 * Если #root отсутствует, React-приложение невозможно запустить.
 *
 * Ошибку лучше показать явно, чем получить непонятную
 * ошибку глубоко внутри React.
 */
if (!rootElement) {

  throw new Error(
    'Kafka System Control: root element "#root" was not found.'
  );

}


/* =============================================================================
   Создание React Root
============================================================================= */

const root = ReactDOM.createRoot(rootElement);


/* =============================================================================
   Монтирование React-приложения
============================================================================= */

root.render(

  <React.StrictMode>

    <ThemeProvider>

      <LanguageProvider>

        <LoadingDemo />

      </LanguageProvider>

    </ThemeProvider>

  </React.StrictMode>

);


